const exec = promisify(execFile);

export interface AppliedEdit { findingIndex: number; action: PlannedEdit["action"]; files: string[]; repaired: boolean }
export interface SkippedEdit { findingIndex: number; reason: string }
export interface ApplyResult {
  applied: AppliedEdit[];
  skipped: SkippedEdit[];
  /** Files the gate should treat as the edit set (applied edits only). */
  editSet: string[];
  /** Wonder repair turns taken. LES-21: always 0 — codemods need no repair turn. */
  repairCalls: number;
  repairUsage?: { prompt_tokens?: number; completion_tokens?: number; total_tokens?: number };
}

async function tscErrors(repo: string): Promise<string | null> {
  // tsc without a tsconfig prints help and exits 1 — not a failure.
  // Mirror the gate (repoCommands): only typecheck when the repo
  // has a tsconfig or a typecheck script; a JavaScript checkout
  // with neither has no tsc step to break (LES-27 found this: every
  // codemod edit in a no-tsconfig JS checkout was skipped here).
  let hasTsc = existsSync(join(repo, "tsconfig.json"));
  if (!hasTsc) {
    try {
      const pkg = JSON.parse(readFileSync(join(repo, "package.json"), "utf8")) as { scripts?: Record<string, string> };
      hasTsc = Boolean(pkg.scripts?.typecheck ?? pkg.scripts?.tsc);
    } catch { hasTsc = false; }
  }
  if (!hasTsc) return null;
  try {
    await exec("npx", ["tsc", "--noEmit"], { cwd: repo, maxBuffer: 64 * 1024 * 1024 });
    return null;
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string };
    return `${err.stdout ?? ""}${err.stderr ?? ""}`.slice(0, 4000) || "tsc failed";
  }
}

async function gitShow(repo: string, ref: string, file: string): Promise<string | null> {
  try {
    const { stdout } = await exec("git", ["show", `${ref}:${file}`], { cwd: repo, maxBuffer: 64 * 1024 * 1024 });
    return stdout;
  } catch { return null; }
}

interface Snapshot { file: string; content: string | null }
const snap = (repo: string, files: string[]): Snapshot[] =>
  files.map((file) => ({ file, content: existsSync(join(repo, file)) ? readFileSync(join(repo, file), "utf8") : null }));
function restore(repo: string, snaps: Snapshot[]): void {
  for (const s of snaps) {
    if (s.content === null) rmSync(join(repo, s.file), { force: true });
    else writeFileSync(join(repo, s.file), s.content);
  }
}
function writeEdit(repo: string, files: { file: string; content: string }[], deleteFiles: string[]): void {
  for (const f of files) writeFileSync(join(repo, f.file), f.content);
  for (const f of deleteFiles) rmSync(join(repo, f), { force: true });
}

/**
 * Apply planned edits one at a time. LES-21: for inline/retarget the
 * file contents are generated by AST codemods (src/plan/codemod.ts) —
 * never by the model — and no repair turn exists: a codemod that
 * cannot be expressed mechanically, or whose result fails tsc, is
 * skipped (reverted) instead of repaired. Any model-supplied content
 * still present on an edit (older plans) is checked by the
 * unrelated-change guard and refused when it alters a statement
 * outside the targeted symbol or its imports. restore-from-base and
 * convention-fix contents always came from code. The gate runs
 * afterwards, on the result.
 */
export async function applyPlan(opts: {
  checkoutDir: string;
  baseRef: string;
  findings: readonly AnyFinding[];
  edits: readonly PlannedEdit[];
  /** Unused since LES-21 (kept for caller compatibility): no repair turn is ever taken. */
  client?: GuestClient;
  runTsc?: (repo: string) => Promise<string | null>;
}): Promise<ApplyResult> {
  const checkTsc = opts.runTsc ?? tscErrors;
  const applied: AppliedEdit[] = [];
  const skipped: SkippedEdit[] = [];
  const repairCalls = 0;

  // Wrapper chains inline outermost-first: an inner layer's call
  // site is only expressible after the outer wrapper's construction
  // has been substituted into the surviving caller. `attemptEdit`
  // returns "defer" for a not-yet-expressible codemod; deferred edits
  // are retried after each full pass while any edit applied. Retarget
  // codemods rewrite every importer themselves, so no repair turn
  // is ever needed for a missed importer.
  const queue: PlannedEdit[] = [...opts.edits];
  for (let pass = 0; pass <= opts.edits.length; pass++) {
    let appliedThisPass = 0;
    const stillDeferred: PlannedEdit[] = [];
    for (const edit of queue) {
      const outcome = await attemptEdit(edit, pass < opts.edits.length);
      if (outcome === "applied") appliedThisPass++;
      else if (outcome === "defer") stillDeferred.push(edit);
    }
    queue.length = 0;
    queue.push(...stillDeferred);
    if (!queue.length || !appliedThisPass) break;
  }

  async function attemptEdit(edit: PlannedEdit, mayDefer: boolean): Promise<"applied" | "skipped" | "defer"> {
    const finding = opts.findings[edit.findingIndex]!;

    if (edit.action === "restore-from-base") {
      const before = snap(opts.checkoutDir, [finding.file]);
      const base = await gitShow(opts.checkoutDir, opts.baseRef, finding.file);
      if (base === null) rmSync(join(opts.checkoutDir, finding.file), { force: true });
      else writeFileSync(join(opts.checkoutDir, finding.file), base);
      const err = await checkTsc(opts.checkoutDir);
      if (err) { restore(opts.checkoutDir, before); skipped.push({ findingIndex: edit.findingIndex, reason: `restore broke tsc, reverted: ${err.split("\n")[0]}` }); return "skipped"; }
      applied.push({ findingIndex: edit.findingIndex, action: edit.action, files: [finding.file], repaired: false });
      return "applied";
    }

    if (edit.action === "convention-fix") {
      if (finding.category !== "convention-break") { skipped.push({ findingIndex: edit.findingIndex, reason: "convention-fix on non-convention finding" }); return "skipped"; }
      // Applied only from the repository convention registry.
      if (!finding.convention || !loadRepositoryConventions(opts.checkoutDir).includes(finding.convention)) {
        skipped.push({ findingIndex: edit.findingIndex, reason: `convention "${finding.convention ?? "(none)"}" is not in the repository convention registry; note only, not applied` });
        return "skipped";
      }
      const fixed = applyConventionFix(opts.checkoutDir, finding);
      if (fixed === undefined) { skipped.push({ findingIndex: edit.findingIndex, reason: "mechanical fix changed nothing; refused" }); return "skipped"; }
      const before = snap(opts.checkoutDir, [finding.file]);
      writeFileSync(join(opts.checkoutDir, finding.file), fixed);
      const err = await checkTsc(opts.checkoutDir);
      if (err) { restore(opts.checkoutDir, before); skipped.push({ findingIndex: edit.findingIndex, reason: `convention fix broke tsc, reverted: ${err.split("\n")[0]}` }); return "skipped"; }
      applied.push({ findingIndex: edit.findingIndex, action: edit.action, files: [finding.file], repaired: false });
      return "applied";
    }

    // inline / retarget: code-generated AST codemod contents.
    if (finding.category !== "single-use-abstraction" && finding.category !== "duplicate-helper") {
      skipped.push({ findingIndex: edit.findingIndex, reason: `${edit.action} on ${finding.category} finding is not a codemod action` });
      return "skipped";
    }
    const wrapperFile = normaliseRepoPath(opts.checkoutDir, finding.file);
    if (!wrapperFile || isSealedPath(wrapperFile)) {
      skipped.push({ findingIndex: edit.findingIndex, reason: `codemod: cited file ${finding.file} is not an in-checkout source file` });
      return "skipped";
    }

    // Unrelated-change guard for any model-supplied content that
    // remains on the edit: it is never written, but when it disagrees
    // with the codemod's targeted change the finding is refused
    // outright (a rewrite that also alters an unrelated statement).
    const sources = loadSources(opts.checkoutDir);
    const targetEntry = sources.get(wrapperFile);
    const target = targetEntry && "citations" in finding ? findTarget(targetEntry.sf, wrapperFile, finding) : undefined;
    if (!targetEntry || !target) {
      skipped.push({ findingIndex: edit.findingIndex, reason: `codemod: no declaration in ${wrapperFile} overlaps the citations` });
      return "skipped";
    }

    let result: CodemodResult | undefined;
    if (edit.action === "inline") {
      result = inlineCodemod(target, wrapperFile, sources);
    } else {
      if (finding.category !== "duplicate-helper" || !finding.existingHelperFile) {
        skipped.push({ findingIndex: edit.findingIndex, reason: "retarget codemod: finding names no existing helper file" });
        return "skipped";
      }
      const helperFile = normaliseRepoPath(opts.checkoutDir, finding.existingHelperFile);
      if (!helperFile || isSealedPath(helperFile) || !sources.has(helperFile)) {
        skipped.push({ findingIndex: edit.findingIndex, reason: `retarget codemod: existing helper ${finding.existingHelperFile} is not a readable source file` });
        return "skipped";
      }
      result = retargetCodemod({ name: target.name, file: wrapperFile }, helperFile, sources);
    }
    if (!result) {
      // Not yet expressible may just mean a wrapper-chain edit must
      // land first (outermost-first); defer while other edits remain
      // that could change the tree, then skip for good.
      if (mayDefer) return "defer";
      skipped.push({ findingIndex: edit.findingIndex, reason: `codemod: ${edit.action} of ${target.name} in ${wrapperFile} cannot be expressed as a mechanical AST edit; finding skipped` });
      return "skipped";
    }

    // Guard: refuse when the model ALSO supplied contents for a file
    // the codemod rewrites and those contents alter a statement
    // outside the targeted symbol or its imports.
    const codemodFiles = new Map(result.newFiles.map((f) => [f.file, f.content]));
    let guardReason: string | undefined;
    for (const supplied of edit.newFiles) {
      if (!codemodFiles.has(supplied.file)) {
        guardReason = `model supplied contents for ${supplied.file}, which the ${edit.action} codemod does not rewrite; refusing model-written file contents`;
        break;
      }
      const beforeText = sources.get(supplied.file)?.text;
      if (beforeText === undefined) continue;
      // Statements the codemod itself rewrites in this file may differ;
      // anything else the model changed is unrelated.
      guardReason = unrelatedChangeReason(supplied.file, beforeText, supplied.content, target.name, statementDiffKeys(beforeText, codemodFiles.get(supplied.file)!, supplied.file));
      if (guardReason) break;
    }
    if (guardReason) {
      skipped.push({ findingIndex: edit.findingIndex, reason: `unrelated-change guard: ${guardReason}` });
      return "skipped";
    }

    const touched = [...new Set([...result.newFiles.map((f) => f.file), ...result.deleteFiles])];
    const before = snap(opts.checkoutDir, touched);
    writeEdit(opts.checkoutDir, result.newFiles, result.deleteFiles);
    const err = await checkTsc(opts.checkoutDir);
    if (err) {
      restore(opts.checkoutDir, before);
      skipped.push({ findingIndex: edit.findingIndex, reason: `codemod broke tsc, finding skipped (no repair turn): ${err.split("\n")[0]}` });
      return "skipped";
    }
    applied.push({ findingIndex: edit.findingIndex, action: edit.action, files: touched, repaired: false });
    return "applied";
  }

  const editSet = [...new Set(applied.flatMap((a) => a.files))];
  return { applied, skipped, editSet, repairCalls };
}

